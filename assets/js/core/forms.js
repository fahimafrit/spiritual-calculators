  const byId = (id) => document.getElementById(id);

  /* "dd/mm/yyyy" typed by the visitor -> "yyyy-mm-dd" for the server,
     or '' while the date is incomplete. */
  function isoDate(text) {
    const m = /^(\d{2})\/(\d{2})\/(\d{4})$/.exec(String(text).trim());
    return m ? `${m[3]}-${m[2]}-${m[1]}` : '';
  }

  const TIME_OK = /^([01]\d|2[0-3]):[0-5]\d$/;

  function setHint(prefix, text) {
    const el = byId(prefix + '_hint');
    if (el) el.textContent = text;
  }

  /* Shows the time zone the server worked out for a person, without
     overwriting one the visitor entered or the city search supplied. */
  function setTimeZone(prefix, tz) {
    const input = byId(prefix + '_tz');
    if (!input || !tz) return;
    if (!input.value) input.value = tz;
  }

  function readValues(fields) {
    const values = {};
    fields.forEach((f) => {
      const input = byId(f.id);
      values[f.id] = input ? input.value : '';
      if (f.type === 'place') {
        ['lat', 'lon', 'tz'].forEach((k) => { values[`${f.prefix}_${k}`] = byId(`${f.prefix}_${k}`).value; });
      }
    });
    return values;
  }

  /* The flat form fields the PHP handlers read. */
  function serverValues(fields, values) {
    const out = {};
    fields.forEach((f) => {
      if (f.type === 'name') out[f.id] = String(values[f.id] || '').trim();
      else if (f.type === 'date') out[f.id] = isoDate(values[f.id]);
      else if (f.type === 'time') out[f.id] = String(values[f.id] || '').trim();
      else if (f.type === 'place') {
        out[`${f.prefix}_lat`] = String(values[`${f.prefix}_lat`] || '').trim();
        out[`${f.prefix}_lon`] = String(values[`${f.prefix}_lon`] || '').trim();
        out[`${f.prefix}_tz`] = String(values[`${f.prefix}_tz`] || '').trim();
      } else if (f.type === 'select') out[f.param] = values[f.id];
    });
    return out;
  }

  /* First missing or malformed required entry, as a message, or ''. */
  function firstProblem(fields, server, values, optional) {
    if (optional) return firstProblemOptional(fields, server, values);
    const say = (person, text) => (person.msgLabel ? `${person.msgLabel}: ${text}` : text.charAt(0).toUpperCase() + text.slice(1));
    for (const f of fields) {
      const p = f.person;
      if (!p) continue;
      if (f.type === 'date' && !server[f.id]) return say(p, 'enter a birth date.');
      if (f.type === 'time' && !TIME_OK.test(server[f.id])) return say(p, 'enter a birth time.');
      if (f.type === 'place' && (server[`${f.prefix}_lat`] === '' || server[`${f.prefix}_lon`] === '')) {
        return say(p, 'search for a birth place or enter latitude and longitude.');
      }
    }
    return '';
  }

  /* Optional-time-and-place forms: the date is required and follows the
     shared date rules; a time is only useful with a place (its time zone). */
  function firstProblemOptional(fields, server, values) {
    let time = '', hasPlace = false;
    for (const f of fields) {
      if (f.type === 'date') {
        const r = checkDate(values[f.id], { birth: true });
        if (r.error) return r.error;
      } else if (f.type === 'time') {
        time = server[f.id];
        if (time !== '' && !TIME_OK.test(time)) return 'Enter the birth time as hh:mm, or leave it empty.';
      } else if (f.type === 'place') {
        const lat = server[`${f.prefix}_lat`], lon = server[`${f.prefix}_lon`];
        if ((lat !== '') !== (lon !== '')) return 'Enter both latitude and longitude, or search for a birth place.';
        hasPlace = lat !== '' && lon !== '';
      }
    }
    if (time !== '' && !hasPlace) return 'Add a birth place to go with the birth time, or leave the time empty.';
    return '';
  }

  function wirePlace(field) {
    const p = field.prefix;
    const input = byId(field.id);
    const list = byId(p + '_sug');
    const latIn = byId(p + '_lat'), lonIn = byId(p + '_lon'), tzIn = byId(p + '_tz');
    let results = [], active = -1, timer, seq = 0;

    const close = () => { list.hidden = true; input.setAttribute('aria-expanded', 'false'); active = -1; };
    const open = () => { list.hidden = false; input.setAttribute('aria-expanded', 'true'); };
    const mark = () => {
      [...list.querySelectorAll('li[data-i]')].forEach((li, i) => li.classList.toggle('active', i === active));
    };

    function choose(c) {
      input.value = [c.name, c.sub].filter(Boolean).join(', ');
      latIn.value = Number(c.lat).toFixed(4);
      lonIn.value = Number(c.lon).toFixed(4);
      tzIn.value = c.tz || '';
      setHint(p, 'Coordinates and time zone filled from the city search.');
      close();
    }

    input.addEventListener('input', () => {
      clearTimeout(timer);
      const q = input.value.trim();
      if (q.length < 2) { close(); return; }
      timer = setTimeout(async () => {
        const mine = ++seq;
        try {
          const found = await placeSearch(q);
          if (mine !== seq) return;
          results = found;
          list.innerHTML = found.length
            ? found.map((c, i) => `<li role="option" data-i="${i}">${esc(c.name)}<small>${esc(c.sub)}</small></li>`).join('')
            : '<li class="none">No match. Enter the coordinates below instead.</li>';
        } catch (err) {
          if (mine !== seq) return;
          results = [];
          list.innerHTML = '<li class="none">City search needs an internet connection. Enter the coordinates below instead.</li>';
        }
        active = -1;
        open();
      }, 320);
    });

    input.addEventListener('keydown', (evt) => {
      if (list.hidden || !results.length) return;
      if (evt.key === 'ArrowDown') { evt.preventDefault(); active = Math.min(active + 1, results.length - 1); mark(); }
      else if (evt.key === 'ArrowUp') { evt.preventDefault(); active = Math.max(active - 1, 0); mark(); }
      else if (evt.key === 'Enter' && active >= 0) { evt.preventDefault(); evt.stopPropagation(); choose(results[active]); }
      else if (evt.key === 'Escape') { close(); }
    });

    list.addEventListener('pointerdown', (evt) => {
      const li = evt.target.closest('li[data-i]');
      if (!li) return;
      evt.preventDefault();
      choose(results[Number(li.dataset.i)]);
    });
    input.addEventListener('blur', () => setTimeout(close, 160));

    // typing coordinates by hand invalidates the previous time zone
    [latIn, lonIn].forEach((el) => {
      el.addEventListener('input', () => {
        tzIn.value = '';
        setHint(p, 'Time zone will be detected from these coordinates.');
      });
    });
  }

  function wireBirth(fields, options) {
    options = options || {};
    const submitBtn = byId('submit-btn');

    try {
      const zones = Intl.supportedValuesOf('timeZone');
      byId('fk-tzlist').innerHTML = zones.map((z) => `<option value="${z}">`).join('');
    } catch (err) { /* older browser: free text still works */ }

    // focus order: name -> date -> time -> place
    const focusable = fields.filter((f) => f.type !== 'select');
    focusable.forEach((field, i) => {
      const input = byId(field.id);
      const next = byId(focusable[i + 1] ? focusable[i + 1].id : '');
      const nextOfSame = next && focusable[i + 1].person === field.person ? next : null;

      if (field.type === 'date') {
        input.addEventListener('input', (evt) => maskDateInput(evt, nextOfSame ? () => nextOfSame.focus() : undefined));
      } else if (field.type === 'time') {
        input.addEventListener('input', (evt) => maskTimeInput(evt, nextOfSame ? () => nextOfSame.focus() : undefined));
      } else if (field.type === 'place') {
        wirePlace(field);
        return; // Enter inside the search box belongs to the suggestion list
      }
      input.addEventListener('keydown', (evt) => {
        if (evt.key === 'Enter') submitBtn.click();
      });
    });

    const example = byId('fk-example');
    if (example && fields.example) {
      example.addEventListener('click', () => {
        Object.keys(fields.example).forEach((id) => {
          const el = byId(id);
          if (el) el.value = fields.example[id];
        });
      });
    }

    submitBtn.addEventListener('click', (evt) => {
      evt.preventDefault();
      if (typeof options.onError === 'function') options.onError('');
      const values = readValues(fields);
      const server = serverValues(fields, values);
      const problem = firstProblem(fields, server, values, !!(fields.layout && fields.layout.optional));
      if (problem) {
        if (typeof options.onError === 'function') options.onError(problem);
        return;
      }
      if (typeof options.onSubmit === 'function') options.onSubmit(values, server);
    });

    return { submitBtn };
  }

  /* ---- prefillFromUrl(fields, onFound) --------------------------------
     If every field's URL param is present (e.g. ?dob=12-03-1990 or
     ?dob1=...&dob2=...), fills the inputs and calls onFound(values) so
     the calculator can run the calculation immediately — the shared
     "open a link, see your result with no click required" behavior. */
  function prefillFromUrl(fields, onFound) {
    const params = new URLSearchParams(window.location.search);
    const values = {};
    const isBirth = !!(fields.layout && fields.layout.birth);

    for (const field of fields) {
      const raw = params.get(field.urlParam);
      if (raw == null) {
        if (isBirth) {
          const input = document.getElementById(field.id);
          if (input) values[field.id] = input.value;
          continue;
        }
        return; // classic layouts: require every field's param
      }
      values[field.id] = field.type === 'date' ? raw.replace(/-/g, '/') : raw;
      if (field.type === 'place') {
        const p = field.prefix;
        ['lat', 'lon', 'tz'].forEach((k) => {
          const v = params.get(`${p}_${k}`);
          if (v != null) values[`${p}_${k}`] = v;
        });
      }
    }

    // Birth-data forms: require at least the date field
    if (isBirth) {
      const dateField = fields.find((f) => f.type === 'date');
      if (!dateField || !values[dateField.id]) return;
    }

    fields.forEach((field) => {
      const input = document.getElementById(field.id);
      if (input && values[field.id] != null) input.value = values[field.id];
      if (field.type === 'place') {
        const p = field.prefix;
        ['lat', 'lon', 'tz'].forEach((k) => {
          const el = document.getElementById(`${p}_${k}`);
          if (el && values[`${p}_${k}`] != null) el.value = values[`${p}_${k}`];
        });
      }
    });

    if (typeof onFound === 'function') onFound(values);
  }

  /* ---- updateUrlParams(fields, values) --------------------------------
     Swaps the shareable-link URL params in place after a successful
     calculation (no reload — everything is recalculated client-side
     from the URL, nothing is stored server-side). */
  function updateUrlParams(fields, values) {
    const url = new URL(window.location.href);
    const isBirth = !!(fields.layout && fields.layout.birth);
    fields.forEach((field) => {
      if (!field.urlParam) return;
      const raw = values[field.id];
      if (raw == null) return;
      if (isBirth && raw === '') return; // skip empty values for birth-data forms
      url.searchParams.set(field.urlParam, field.type === 'date' ? String(raw).replace(/\//g, '-') : raw);
      if (field.type === 'place') {
        const p = field.prefix;
        ['lat', 'lon', 'tz'].forEach((k) => {
          const v = values[`${p}_${k}`];
          if (v != null && v !== '') url.searchParams.set(`${p}_${k}`, v);
        });
      }
    });
    window.history.pushState({}, '', url);
  }

  return { LAYOUTS, render, wire, maskDateInput, parseDate, checkDate, prefillFromUrl, updateUrlParams, setTimeZone, setPlaceSearch, serverValues };
